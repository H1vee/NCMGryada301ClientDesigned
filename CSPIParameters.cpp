VOID CSPIParameters::GOST28147(
							  FILE* pFile,
							  GOST28147_COMPRESSED_SBOX pSBox)
{
	DWORD dw, dw1, dw2;

	memset((PVOID) pSBox, 0, sizeof(GOST28147_COMPRESSED_SBOX));

	CHAR sz[16384];

	fscanf(pFile, "%s", sz);

	for(dw1 = 0; dw1 < 4; dw1++)
	{
		for(dw2 = 0; dw2 < 16; dw2++)
		{
			fscanf(pFile, "%X", &dw);
			pSBox[dw1 * 16 + dw2] |= (BYTE) (dw & 0xF);
		}

		for(dw2 = 0; dw2 < 16; dw2++)
		{
			fscanf(pFile, "%X", &dw);
			pSBox[dw1 * 16 + dw2] |= (BYTE) (dw << 4);
		}
	}
}

