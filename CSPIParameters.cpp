BOOL CSPIParameters::OpenFile(
	PCSTR	pszFileName,
	DWORD	dwDesiredAccess,
	DWORD	dwShareMode,
	DWORD	dwCreationDisposition,
	DWORD	dwFlagsAndAttributes,
	PHANDLE	phFile)
{
	HANDLE hFile;

#ifndef OS_NIX
	PWCHAR pwszFileName;
	INT nFileNameSize;

	nFileNameSize = (INT) strlen(pszFileName) + 1;

	pwszFileName = new WCHAR[nFileNameSize];
	if (pwszFileName == NULL)
		return FALSE;

	if (MultiByteToWideChar(1251, 0,
			pszFileName, nFileNameSize,
			pwszFileName, nFileNameSize) !=
		nFileNameSize)
	{
		delete[] pwszFileName;
		return FALSE;
	}

	hFile = CreateFileW(pwszFileName, dwDesiredAccess,
		dwShareMode, NULL, dwCreationDisposition,
		dwFlagsAndAttributes, NULL);

	delete[] pwszFileName;
#else // OS_NIX
	hFile = CreateFileA(pszFileName, dwDesiredAccess,
		dwShareMode, NULL, dwCreationDisposition,
		dwFlagsAndAttributes, NULL);
#endif // OS_NIX

	if(hFile == INVALID_HANDLE_VALUE)
		return FALSE;

	if (phFile != NULL)
		*phFile = hFile;
	else
		CloseHandle(hFile);

	return TRUE;
}

//----------------------------------------------------------------------------------------------------------------------

BOOL CSPIParameters::ReadDataFromFile(
	PCHAR 	pcFileName,
	PVOID 	pvData,
	DWORD 	cbData)
{
	HANDLE hFile;
	DWORD cb, cbFile;

	if(!OpenFile(pcFileName,
			GENERIC_READ, 0, OPEN_EXISTING,
			FILE_ATTRIBUTE_NORMAL, &hFile))
	{
		return FALSE;
	}

	cbFile = GetFileSize(hFile, NULL);

	if(cbFile == 0xFFFFFFFF ||
		cbFile != cbData)
	{
		CloseHandle(hFile);
		return FALSE;
	}

	if(!ReadFile(hFile, pvData, cbFile, &cb, NULL) ||
		(cbFile != cb))
	{
		CloseHandle(hFile);
		return FALSE;
	}

	CloseHandle(hFile);
	return TRUE;
}

//----------------------------------------------------------------------------------------------------------------------

BOOL CSPIParameters::WriteDataToFile(
	PCHAR 	pcFileName,
	PVOID 	pvData,
	DWORD 	cbData)
{
	HANDLE 	hFile;
	DWORD 	cb;

	if(!OpenFile(pcFileName,
			GENERIC_WRITE, 0, CREATE_ALWAYS,
			FILE_ATTRIBUTE_NORMAL |
			FILE_FLAG_WRITE_THROUGH, &hFile))
	{
		return FALSE;
	}

	if(!WriteFile(hFile, pvData, cbData, &cb, NULL) ||
		(cbData != cb))
	{
		CloseHandle(hFile);
		DeleteFileA(pcFileName);
		return FALSE;
	}

	CloseHandle(hFile);
	return TRUE;
}

